//! MT76x0 **PLL frequency plan** — the per-channel RF-bank-0 register program that
//! puts the synthesiser on a channel. Two parallel tables plus the list of channels
//! that must use the second one.
//!
//! ## Provenance: CODE-READ, none of it MEASURED
//! Every number here is a verbatim transcription of the GPL mt76 tree, not a
//! register read off silicon. The oracle sweep on mds-o5p-1's MT7610U covered MAC
//! and BBP counters (TSF, CH_IDLE/CH_BUSY, RX_STAT); it never touched RF bank 0, so
//! nothing in this file has been confirmed against the part.
//!   * `FREQUENCY_PLAN`     ← `mt76x0/initvals_phy.h:320-446` (`mt76x0_frequency_plan`)
//!   * `SDM_FREQUENCY_PLAN` ← `mt76x0/initvals_phy.h:448-574` (`mt76x0_sdm_frequency_plan`)
//!   * `SDM_CHANNEL`        ← `mt76x0/initvals_phy.h:576-584` (`mt76x0_sdm_channel`)
//!   * [`FreqItem`] field order ← `struct mt76x0_freq_item`, `mt76x0/phy.h:53-74`
//!
//! The C initialisers are positional, so a single dropped or transposed column
//! silently mis-programs the synthesiser on every channel. The transcription was
//! generated mechanically from the header and is pinned by the column-shape tests
//! at the bottom of this file, which assert the constant-valued columns each table
//! actually has (e.g. every integer-N row has `pll_r28_b5b4 == 0x30`, every SDM row
//! has `pll_r28_b3b2 == 0x8`). Those tests exist to fail loudly on a shift.
//!
//! ## Why there are two tables
//! Upstream states no reason, but the data does: all 125 rows of `FREQUENCY_PLAN`
//! all carry `pll_sdm_k == 0` and `pll_r30_b1 == 1`, and `pll_r30_b1` is the
//! sigma-delta **bypass** bit (`sdm_bp`, `mt76x0/phy.h:67`). The SDM rows clear that
//! bit and carry a nonzero fractional numerator in `pll_sdm_k`. So the default plan
//! runs the PLL integer-N with the SDM modulator bypassed, and the 26 channels
//! named in [`SDM_CHANNEL`] instead run fractional-N. Which 26 those are is a
//! silicon fact we cannot derive — port the list faithfully.
//!
//! ## The index-parallel trap
//! Upstream never searches the SDM table. It finds the channel's index `i` in
//! `mt76x0_frequency_plan` and then reads `mt76x0_sdm_frequency_plan[i]`
//! (`mt76x0/phy.c:251-258`). Both tables must therefore stay 125 rows long in
//! *identical channel order*, or the driver programs a different channel than it
//! asked for — with no error anywhere. [`lookup`] reproduces that indexing exactly,
//! and `tables_are_index_parallel` enforces the invariant.
//!
//! Upstream also takes the band mask from the *non*-SDM row regardless of which
//! plan it uses (`mt76x0/phy.c:253`); here the two tables' `band` columns are equal
//! index-wise anyway, which the same test asserts.
//!
//! ## How the fields reach the chip (`mt76x0/phy.c:260-332`)
//! Most `pll_rNN_bXbY` values are stored **pre-shifted into their bit field** and
//! are RMW'd in against a mask with no further shift — e.g. `pll_r32_b7b5 = 0x40`
//! goes in under mask `0xe0` (`phy.c:266-267`). Three exceptions:
//!   * `pll_r30_b1` is written as `<< 1` (`phy.c:300`);
//!   * `pll_n` is split — low 8 bits to RF(0,29), bit 8 to RF(0,30) (`phy.c:304-307`);
//!   * `pll_sdm_k` is split across RF(0,26)/RF(0,27)/RF(0,28) as `[7:0]`, `[15:8]`,
//!     `[17:16]` (`phy.c:323-328`).
//!
//! This module only stores the numbers; the shifting/splitting belongs to `phy.rs`.
//!
//! The MT7610U is 1×1 **dual-band**, so both the 2.4 GHz and 5 GHz rows are live for
//! our part. The 802.11j 4.9 GHz rows (channels 183-196) are transcribed for
//! completeness; whether they may lawfully be keyed is a regulatory question this
//! file does not answer.


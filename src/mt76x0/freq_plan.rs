/// The channels that must be programmed from [`SDM_FREQUENCY_PLAN`] instead of
/// [`FREQUENCY_PLAN`].
///
/// `mt76x0_sdm_channel[]`, `mt76x0/initvals_phy.h:576-584`. **Not sorted** —
/// upstream groups it four-per-line with the 4.9 GHz pair first, and the grouping
/// is preserved here. Do not "tidy" it into ascending order without re-checking
/// against the header; `sdm_channel_is_not_sorted` pins the fact so a future reader
/// does not mistake the disorder for a transcription slip.
pub const SDM_CHANNEL: &[u8] = &[
    183, 185, 43, 45, 54, 55, 57, 58, 102, 103, 105, 106, 115, 117, 126, 127, 129, 130, 139, 141,
    150, 151, 153, 154, 163, 165,
];

/// Does `channel` need the fractional-N plan?
///
/// Linear scan of [`SDM_CHANNEL`], exactly as `mt76x0/phy.c:244-249`. 26 entries,
/// so the scan is cheaper than anything cleverer and keeps the shape auditable.
pub fn uses_sdm(channel: u8) -> bool {
    SDM_CHANNEL.contains(&channel)
}

/// The PLL program for `channel`, from the SDM table when `use_sdm`.
///
/// Reproduces `mt76x0/phy.c:251-258` including its indexing discipline: the channel
/// is found **only** in [`FREQUENCY_PLAN`], and the SDM row is taken at that same
/// index. Returns `None` for a channel the silicon has no plan for — upstream's
/// loop simply falls through and leaves `freq_item` uninitialised, which we will
/// not imitate.
///
/// Callers normally pair this with [`uses_sdm`]:
/// `lookup(ch, uses_sdm(ch))`. Note that upstream reads the band mask from the
/// non-SDM row regardless (`phy.c:253`); the two tables agree on `band` at every
/// index, so either row answers that question.
pub fn lookup(channel: u8, use_sdm: bool) -> Option<&'static FreqItem> {
    let idx = FREQUENCY_PLAN.iter().position(|it| it.channel == channel)?;
    if use_sdm {
        SDM_FREQUENCY_PLAN.get(idx)
    } else {
        FREQUENCY_PLAN.get(idx)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Row counts as counted in `initvals_phy.h`. A short table means the
    /// transcription dropped a line.
    #[test]
    fn table_lengths() {
        assert_eq!(FREQUENCY_PLAN.len(), 125);
        assert_eq!(SDM_FREQUENCY_PLAN.len(), 125);
        assert_eq!(SDM_CHANNEL.len(), 26);
    }

    /// The invariant [`lookup`] rests on: upstream indexes the SDM table with the
    /// index it found in the non-SDM table (`mt76x0/phy.c:251-258`), so the two
    /// must agree on channel — and, as a bonus check on the band column, on band.
    #[test]
    fn tables_are_index_parallel() {
        for (i, (a, b)) in FREQUENCY_PLAN.iter().zip(SDM_FREQUENCY_PLAN).enumerate() {
            assert_eq!(a.channel, b.channel, "channel mismatch at row {i}");
            assert_eq!(a.band, b.band, "band mismatch at row {i}");
        }
    }

    /// `lookup` scans for the *first* matching channel, so a duplicate would make
    /// one row unreachable and mask a transcription error.
    #[test]
    fn channels_are_unique() {
        let mut seen = std::collections::HashSet::new();
        for it in FREQUENCY_PLAN {
            assert!(seen.insert(it.channel), "duplicate channel {}", it.channel);
        }
    }

    /// Every `channel` is a real 802.11 channel number, and its band mask agrees
    /// with the range it falls in: 1-14 is 2.4 GHz, 36-64 / 100-173 is 5 GHz,
    /// 183-196 is the 4.9 GHz 802.11j allocation.
    #[test]
    fn channels_are_plausible() {
        for it in FREQUENCY_PLAN {
            let g = it.band & u32::from(RF_G_BAND) != 0;
            let a = it.band & u32::from(RF_A_BAND) != 0;
            assert!(g ^ a, "channel {} is in neither or both bands", it.channel);
            if g {
                assert!(
                    (1..=14).contains(&it.channel),
                    "G-band channel {} out of range",
                    it.channel
                );
            } else {
                assert!(
                    matches!(it.channel, 36..=64 | 100..=173 | 183..=196),
                    "A-band channel {} out of range",
                    it.channel
                );
            }
        }
    }

    /// Exactly one sub-band qualifier per 5 GHz row, and the 2.4 GHz rows carry
    /// none. Catches an OR expression transcribed with the wrong flag.
    #[test]
    fn a_band_rows_carry_one_sub_band() {
        for it in FREQUENCY_PLAN {
            let subs = [RF_A_BAND_LB, RF_A_BAND_MB, RF_A_BAND_HB, RF_A_BAND_11J]
                .iter()
                .filter(|f| it.band & u32::from(**f) != 0)
                .count();
            let expect = usize::from(it.band & u32::from(RF_A_BAND) != 0);
            assert_eq!(subs, expect, "channel {} sub-band flags", it.channel);
        }
    }

    /// Column shape of the integer-N table. These columns are single-valued across
    /// all 125 rows in `initvals_phy.h:320-446`; if a field shifted during
    /// transcription, at least one of them stops being constant.
    #[test]
    fn integer_n_column_shape() {
        for it in FREQUENCY_PLAN {
            assert_eq!(it.pll_r37, 0x02, "ch {}", it.channel);
            assert_eq!(it.pll_r36, 0x3F, "ch {}", it.channel);
            assert_eq!(it.pll_r32_b7b5, 0x40, "ch {}", it.channel);
            assert_eq!(it.pll_r31_b7b5, 0x40, "ch {}", it.channel);
            assert_eq!(it.pll_r30_b7, 0, "ch {}", it.channel);
            assert_eq!(it.pll_r30_b6b2, 0, "ch {}", it.channel);
            // sdm_bp set: the sigma-delta modulator is bypassed on this plan.
            assert_eq!(it.pll_r30_b1, 1, "ch {}", it.channel);
            assert_eq!(it.pll_r28_b7b6, 0, "ch {}", it.channel);
            assert_eq!(it.pll_r28_b5b4, 0x30, "ch {}", it.channel);
            assert_eq!(it.pll_r28_b3b2, 0, "ch {}", it.channel);
            // ...and with the modulator bypassed the numerator is unused.
            assert_eq!(it.pll_sdm_k, 0, "ch {}", it.channel);
            assert!(
                matches!(it.pll_r35, 0x28 | 0x30 | 0x3C | 0x68 | 0x70),
                "ch {} pll_r35 {:#04x}",
                it.channel,
                it.pll_r35
            );
            assert!(matches!(it.pll_r34, 0x97 | 0xDD), "ch {}", it.channel);
            assert!(
                matches!(it.pll_r33, 0xD2 | 0xD4 | 0xE2 | 0xE4 | 0xF2),
                "ch {} pll_r33 {:#04x}",
                it.channel,
                it.pll_r33
            );
            assert!(
                matches!(it.pll_r24_b1b0, 0x0 | 0x1 | 0x3),
                "ch {}",
                it.channel
            );
        }
    }

    /// Column shape of the fractional-N table (`initvals_phy.h:448-574`), which is
    /// far more uniform: only `pll_n` and `pll_sdm_k` vary from row to row.
    #[test]
    fn sdm_column_shape() {
        for it in SDM_FREQUENCY_PLAN {
            assert_eq!(it.pll_r37, 0x02, "ch {}", it.channel);
            assert_eq!(it.pll_r36, 0x3F, "ch {}", it.channel);
            assert_eq!(it.pll_r35, 0x7F, "ch {}", it.channel);
            assert_eq!(it.pll_r34, 0xDD, "ch {}", it.channel);
            assert_eq!(it.pll_r33, 0xC3, "ch {}", it.channel);
            assert_eq!(it.pll_r32_b7b5, 0x40, "ch {}", it.channel);
            assert_eq!(it.pll_r32_b4b0, 0, "ch {}", it.channel);
            assert_eq!(it.pll_r31_b7b5, 0x80, "ch {}", it.channel);
            assert_eq!(it.pll_r31_b4b0, 0, "ch {}", it.channel);
            assert_eq!(it.pll_r30_b7, 0, "ch {}", it.channel);
            assert_eq!(it.pll_r30_b6b2, 0, "ch {}", it.channel);
            // sdm_bp clear: the modulator is engaged, so pll_sdm_k is live.
            assert_eq!(it.pll_r30_b1, 0, "ch {}", it.channel);
            assert_eq!(it.pll_r28_b7b6, 0, "ch {}", it.channel);
            assert_eq!(it.pll_r28_b5b4, 0, "ch {}", it.channel);
            assert_eq!(it.pll_r28_b3b2, 0x8, "ch {}", it.channel);
            assert_eq!(it.pll_r24_b1b0, 0x3, "ch {}", it.channel);
            // 18 bits: RF(0,28)[1:0] : RF(0,27) : RF(0,26), phy.c:323-328.
            assert!(it.pll_sdm_k < (1 << 18), "ch {} sdm_k too wide", it.channel);
        }
    }

    /// `pll_n` is 9 bits — RF(0,30) bit 0 plus RF(0,29) (`mt76x0/phy.c:304-307`).
    #[test]
    fn pll_n_fits_nine_bits() {
        for it in FREQUENCY_PLAN.iter().chain(SDM_FREQUENCY_PLAN) {
            assert!(
                it.pll_n < (1 << 9),
                "ch {} pll_n {:#x}",
                it.channel,
                it.pll_n
            );
        }
    }

    /// Every channel named in [`SDM_CHANNEL`] must actually have a row to be read,
    /// otherwise [`lookup`] would hand back a fractional-N program for the wrong
    /// frequency (or, upstream, uninitialised memory).
    #[test]
    fn sdm_channels_have_sdm_rows() {
        for &ch in SDM_CHANNEL {
            assert!(
                SDM_FREQUENCY_PLAN.iter().any(|it| it.channel == ch),
                "SDM channel {ch} has no row in SDM_FREQUENCY_PLAN"
            );
            assert!(
                FREQUENCY_PLAN.iter().any(|it| it.channel == ch),
                "SDM channel {ch} has no row in FREQUENCY_PLAN"
            );
        }
    }

    /// Documents, rather than fixes, the upstream ordering: `mt76x0_sdm_channel[]`
    /// is **not** ascending (it opens `183, 185, 43, 45`). A future reader who
    /// "corrects" it will fail this test and go read the header.
    #[test]
    fn sdm_channel_is_not_sorted() {
        assert!(
            SDM_CHANNEL.windows(2).any(|w| w[0] > w[1]),
            "SDM_CHANNEL became sorted — did someone reorder the transcription?"
        );
        let mut sorted = SDM_CHANNEL.to_vec();
        sorted.sort_unstable();
        sorted.dedup();
        assert_eq!(sorted.len(), SDM_CHANNEL.len(), "duplicate in SDM_CHANNEL");
    }

    /// End-to-end on channel 43, which is in [`SDM_CHANNEL`]: the two tables give
    /// genuinely different programs, and `lookup` picks the one asked for.
    #[test]
    fn lookup_picks_the_requested_table() {
        assert!(uses_sdm(43));
        assert!(!uses_sdm(36));

        let plain = lookup(43, false).expect("ch 43 in FREQUENCY_PLAN");
        let sdm = lookup(43, true).expect("ch 43 in SDM_FREQUENCY_PLAN");
        assert_eq!(plain.channel, 43);
        assert_eq!(sdm.channel, 43);
        assert_eq!(plain.pll_r35, 0x68);
        assert_eq!(sdm.pll_r35, 0x7F);
        assert_eq!(plain.pll_sdm_k, 0);
        assert_eq!(sdm.pll_sdm_k, 0x1D555);

        assert!(lookup(0, false).is_none());
        assert!(lookup(200, true).is_none());
    }

    /// Spot-checks against the header, first and last row of each table, so a
    /// wholesale offset (an off-by-one in the generator) cannot pass.
    #[test]
    fn boundary_rows_match_the_header() {
        let first = &FREQUENCY_PLAN[0];
        assert_eq!(first.channel, 1);
        assert_eq!(first.band, u32::from(RF_G_BAND));
        assert_eq!(first.pll_r35, 0x28);
        assert_eq!(first.pll_n, 0x28);
        assert_eq!(first.pll_r24_b1b0, 0x3);

        let last = &FREQUENCY_PLAN[FREQUENCY_PLAN.len() - 1];
        assert_eq!(last.channel, 173);
        assert_eq!(last.band, u32::from(RF_A_BAND) | u32::from(RF_A_BAND_HB));
        assert_eq!(last.pll_r31_b4b0, 0x15);
        assert_eq!(last.pll_n, 0x30);

        let sdm_first = &SDM_FREQUENCY_PLAN[0];
        assert_eq!(sdm_first.channel, 1);
        assert_eq!(sdm_first.pll_sdm_k, 0x0CCCC);

        let sdm_last = &SDM_FREQUENCY_PLAN[SDM_FREQUENCY_PLAN.len() - 1];
        assert_eq!(sdm_last.channel, 173);
        assert_eq!(sdm_last.pll_sdm_k, 0x38000);
    }
}
